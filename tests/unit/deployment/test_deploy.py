def test_failed_restore_preserves_backup_for_manual_recovery(repository, tmp_path, monkeypatch, package):
    client = tmp_path / "client"
    target = client / "Interface" / "AddOns" / deploy.ADDON
    target.mkdir(parents=True)
    (target / "previous.lua").write_text("previous", encoding="utf-8")
    original_rename = Path.rename

    def fail_install_and_restore(path, destination):
        if path.parent.name.startswith(f".{deploy.ADDON}-"):
            raise PermissionError("simulated locked destination")
        return original_rename(path, destination)

    monkeypatch.setattr(Path, "rename", fail_install_and_restore)
    with pytest.raises(OSError, match="Previous addon preserved at"):
        deploy.deploy_package(package, client, repository)
    backups = list(target.parent.glob(f".{deploy.ADDON}-*/previous/previous.lua"))
    assert len(backups) == 1
    assert backups[0].read_text(encoding="utf-8") == "previous"


def test_build_uses_ci_revision_args_and_packager_output(repository, monkeypatch):
    monkeypatch.setenv("GIT_CONFIG_COUNT", "1")
    monkeypatch.setenv("GIT_CONFIG_KEY_0", "color.ui")
    monkeypatch.setenv("GIT_CONFIG_VALUE_0", "false")
    script = repository / ".release" / "tools" / REVISION / "release.sh"
    script.parent.mkdir(parents=True)
    script.write_text("# cached upstream script", encoding="utf-8")
    monkeypatch.setattr(deploy, "find_bash", lambda explicit: "bash")
    calls = []

    def run_packager(command, **kwargs):
        calls.append((command, kwargs))
        result = repository / ".release" / "local" / deploy.ADDON
        result.mkdir()
        (result / f"{deploy.ADDON}.toc").write_text("## Version: generated", encoding="utf-8")

    monkeypatch.setattr(deploy.subprocess, "run", run_packager)
    package = deploy.build_package(repository)
    assert package == repository / ".release" / "local" / deploy.ADDON
    assert len(calls) == 1
    command, options = calls[0]
    assert command == [
        "bash", f".release/tools/{REVISION}/release.sh", "-p", "1741704",
        "-d", "-z", "-t", ".", "-r", "./.release/local",
    ]
    assert options["cwd"] == repository
    assert options["check"] is True
    assert options["env"]["GIT_CONFIG_COUNT"] == "2"
    assert options["env"]["GIT_CONFIG_KEY_0"] == "color.ui"
    assert options["env"]["GIT_CONFIG_KEY_1"] == "log.showSignature"
    assert options["env"]["GIT_CONFIG_VALUE_1"] == "false"


def test_packager_pin_tracks_release_workflow_changes(repository):
    workflow = repository / ".github" / "workflows" / "release.yml"
    workflow.write_text(workflow.read_text(encoding="utf-8").replace(REVISION, "a" * 40).replace("1741704", "123"), encoding="utf-8")
    assert deploy.packager_configuration(repository) == ("a" * 40, ["-p", "123"])
    workflow.write_text("steps:\n  - uses: BigWigsMods/packager@v2\n", encoding="utf-8")
    with pytest.raises(ValueError, match="full commit SHA"):
        deploy.packager_configuration(repository)


def test_downloads_ci_pinned_script_only_when_uncached(repository, monkeypatch):
    import io

    downloads = []

    def download(url, timeout):
        downloads.append(url)
        return io.BytesIO(b"# upstream Packager\n")

    monkeypatch.setattr(deploy, "urlopen", download)
    monkeypatch.setattr(deploy, "find_bash", lambda explicit: "bash")

    def run_packager(command, **kwargs):
        result = repository / ".release" / "local" / deploy.ADDON
        result.mkdir(exist_ok=True)
        (result / f"{deploy.ADDON}.toc").write_text("## Version: generated", encoding="utf-8")

    monkeypatch.setattr(deploy.subprocess, "run", run_packager)
    deploy.build_package(repository)
    deploy.build_package(repository)
    assert downloads == [f"https://raw.githubusercontent.com/BigWigsMods/packager/{REVISION}/release.sh"]
