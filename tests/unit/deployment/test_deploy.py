def test_package_and_redeploy_replace_stale_files_and_preserve_settings(repository, tmp_path, monkeypatch, stub_packager, package):
    monkeypatch.setattr(deploy, "ROOT", repository)
    wow = tmp_path / "World of Warcraft"
    client = wow / "_retail_"
    target = client / "Interface" / "AddOns" / deploy.ADDON
    target.mkdir(parents=True)
    (target / "obsolete.lua").write_text("old", encoding="utf-8")
    other = target.parent / "OtherAddon"
    other.mkdir()
    (other / "Other.lua").write_text("untouched", encoding="utf-8")
    saved = client / "WTF" / "Account" / "SavedVariables.lua"
    saved.parent.mkdir(parents=True)
    saved.write_text("settings", encoding="utf-8")

    assert deploy.main([str(wow)]) == 0
    assert not (target / "obsolete.lua").exists()
    assert (target / "Main.lua").read_bytes() == (package / "Main.lua").read_bytes()
    assert (other / "Other.lua").read_text(encoding="utf-8") == "untouched"
    assert saved.read_text(encoding="utf-8") == "settings"
    assert (target / "CHANGELOG.md").read_bytes() == (package / "CHANGELOG.md").read_bytes()
    assert not (target / ".env").exists()
    assert deploy.main([str(client)]) == 0
    assert sorted(path.name for path in target.parent.iterdir()) == [deploy.ADDON, "OtherAddon"]


